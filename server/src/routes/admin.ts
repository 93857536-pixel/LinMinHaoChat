/** 错误日志尾部 */
adminRouter.get('/logs', (req, res) => {
  const lines = Math.min(Math.max(Number(req.query.lines || 100), 1), 500);
  const logDir = path.join(config.dataRoot, 'logs');
  const files = fs.readdirSync(logDir).filter((f) => f.startsWith('error.')).sort().reverse();
  const out: string[] = [];
  for (const f of files.slice(0, 3)) {
    try {
      const content = fs.readFileSync(path.join(logDir, f), 'utf8').trim().split('\n');
      out.push(`--- ${f} ---`, ...content.slice(-lines));
    } catch { /* ignore */ }
  }
  res.json({ ok: true, logs: out });
});

