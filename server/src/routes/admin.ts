/** 删除临时房间全部密文(彻底删除) */
adminRouter.delete('/temp-rooms/:id', (req, res) => {
  const id = String(req.params.id);
  const paths = db.prepare('SELECT cipher_path FROM messages WHERE room_id=?').all(id) as { cipher_path: string }[];
  const tx = db.transaction(() => {
    for (const p of paths) store.deleteCipher(p.cipher_path);
    db.prepare('DELETE FROM messages WHERE room_id=?').run(id);
    db.prepare('DELETE FROM temp_rooms WHERE id=?').run(id);
  });
  tx();
  audit('temp_room_delete', `room=${id} messages=${paths.length}`);
  logger.warn('admin_temp_room_deleted', { id, messages: paths.length });
  res.json({ ok: true });
});

