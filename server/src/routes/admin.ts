/** 封禁/解封用户 */
adminRouter.post('/users/:id/ban', (req, res) => {
  const id = Number(req.params.id);
  const ban = Boolean(req.body?.ban);
  if (!Number.isInteger(id) || id <= 0) return res.status(400).json({ error: 'bad_id' });
  db.prepare('UPDATE users SET banned=?, ban_reason=? WHERE id=?').run(ban ? 1 : 0, ban ? String(req.body?.reason || 'admin').slice(0, 200) : null, id);
  audit('user_ban', `user=${id} ban=${ban}`);
  logger.warn('admin_user_banned', { id, ban });
  res.json({ ok: true });
});

/** 删除账号 + 其私聊密文(密文按房间删除) */
adminRouter.delete('/users/:id', (req, res) => {
  const id = Number(req.params.id);
  if (!Number.isInteger(id) || id <= 0) return res.status(400).json({ error: 'bad_id' });
  const roomIds = (db.prepare('SELECT room_id FROM room_members WHERE user_id=?').all(id) as { room_id: string }[]).map((r) => r.room_id);
  const tx = db.transaction(() => {
    const paths = db.prepare('SELECT cipher_path FROM messages WHERE room_id IN (SELECT room_id FROM room_members WHERE user_id=?)').all(id) as { cipher_path: string }[];
    for (const p of paths) store.deleteCipher(p.cipher_path);
    db.prepare('DELETE FROM messages WHERE room_id IN (SELECT room_id FROM room_members WHERE user_id=?)').run(id);
    for (const rid of roomIds) {
      db.prepare('DELETE FROM room_keys WHERE room_id=?').run(rid);
      db.prepare('DELETE FROM room_members WHERE room_id=?').run(rid);
      db.prepare('DELETE FROM rooms WHERE id=? AND NOT EXISTS (SELECT 1 FROM room_members WHERE room_id=?)').run(rid, rid);
    }
    db.prepare('DELETE FROM user_keys WHERE user_id=?').run(id);
    db.prepare('DELETE FROM sessions WHERE user_id=?').run(id);
    db.prepare('DELETE FROM users WHERE id=?').run(id);
  });
  tx();
  audit('user_delete', `user=${id}`);
  logger.warn('admin_user_deleted', { id });
  res.json({ ok: true });
});

