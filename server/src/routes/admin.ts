/** 轮换管理员密码(写回 config/env.json 需管理员自行操作;这里提供工具) */
adminRouter.post('/rotate-password', async (req, res) => {
  const { newPassword } = req.body || {};
  if (typeof newPassword !== 'string' || newPassword.length < 12) {
    return res.status(400).json({ error: 'password_too_short' });
  }
  // 生成新的 .env 片段,提示管理员在服务器配置
  const envPath = path.join(process.cwd(), 'config', 'env.json');
  let env: Record<string, string> = {};
  try { env = JSON.parse(fs.readFileSync(envPath, 'utf8')); } catch { /* ignore */ }
  env.ADMIN_PASSWORD = newPassword;
  fs.writeFileSync(envPath, JSON.stringify(env, null, 2), { mode: 0o600 });
  audit('admin_rotate_password', 'password rotated (config/env.json)');
  res.json({ ok: true, note: 'updated config/env.json; restart service to apply' });
});

