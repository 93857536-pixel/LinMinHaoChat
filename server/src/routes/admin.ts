/**
 * 管理后台:可看元数据/统计/封禁/删除密文,但绝不解密(没有密钥,解密在客户端)。
 * 登录:Basic 凭据(ADMIN_USER/ADMIN_PASSWORD,scrypt 校验)→ 颁发 12h admin JWT。
 */
export const adminRouter = Router();

/** 管理员登录 */
adminRouter.post('/login', async (req, res) => {
  const ip = clientIp(req);
  const r = rateLimit(`admin:login:${ip}`, 5, 10 * 60_000, 10 * 60_000);
  if (!r.ok) return res.status(429).json({ error: 'rate_limited', retryAfterSec: r.retryAfterSec });

  const { username, password } = req.body || {};
  if (String(username || '') !== config.adminUser) return res.status(401).json({ error: 'bad_credentials' });
  if (!scryptVerify(String(password || ''), config.adminPasswordHash)) {
    logger.warn('admin_login_failed', { ip });
    return res.status(401).json({ error: 'bad_credentials' });
  }
  const jwt = await signAdminJwt(config.adminUser);
  logger.info('admin_login', { ip });
  res.json({ ok: true, token: jwt });
});

adminRouter.use(adminAuth);

/** 登录后获取元数据(如管理员首次密码提示) */
adminRouter.get('/me', (_req, res) => {
  res.json({
    ok: true, user: config.adminUser,
    autoGeneratedPassword: config.adminPasswordPlain
      ? `首次自动生成密码位于 ${path.join(config.dataRoot, 'config', 'admin.cred')} (登录后请立即在服务器上修改)`
      : undefined,
  });
});

function audit(action: string, detail: string) {
  db.prepare('INSERT INTO admin_audit (ts, actor, action, detail) VALUES (?,?,?,?)')
    .run(Date.now(), config.adminUser, action, detail);
}

/** 概览统计 */
adminRouter.get('/stats', (_req, res) => {
  const stats = {
    users: (db.prepare('SELECT COUNT(*) AS c FROM users').get() as { c: number }).c,
    bannedUsers: (db.prepare('SELECT COUNT(*) AS c FROM users WHERE banned=1').get() as { c: number }).c,
    online: getOnlineCount(),
    tempRooms: (db.prepare('SELECT COUNT(*) AS c FROM temp_rooms').get() as { c: number }).c,
    activeTempRooms: (db.prepare('SELECT COUNT(*) AS c FROM temp_rooms WHERE status=\'active\' AND expires_at>?').get(Date.now()) as { c: number }).c,
    rooms: (db.prepare('SELECT COUNT(*) AS c FROM rooms').get() as { c: number }).c,
    messages: (db.prepare('SELECT COUNT(*) AS c FROM messages').get() as { c: number }).c,
    sessions: (db.prepare('SELECT COUNT(*) AS c FROM sessions').get() as { c: number }).c,
    uptimeSec: Math.round(process.uptime()),
    memUsedMB: Math.round(process.memoryUsage().rss / 1024 / 1024),
    cpuLoad: os.loadavg()[0],
    disk: store.diskUsageBytes(),
    diskFreeMB: Math.round(os.freemem() / 1024 / 1024),
    dbOk: health(),
    version: '1.0.0',
  };
  res.json({ ok: true, stats });
});

function health(): boolean {
  try { db.prepare('SELECT 1').get(); return true; } catch { return false; }
}

/** 用户列表(脱敏,不含任何聊天内容) */
