import Foundation

/// 强制隐私模式(产品定位第四条):
///
/// - 永久开启:没有关闭按钮、没有设置开关、没有隐藏 API、没有普通用户可使用的关闭方式。
/// - 聊天界面不显示水印。
/// - 私钥只存本机 Keychain,服务器只持有密文。
///
/// 本类型不存在任何"关闭"路径 —— 全 App 唯一的事实来源。
enum PrivacyMode {
    /// 隐私模式状态。恒为 true,任何代码不得改写。
    static let enforced = true

    /// 隐私模式说明文案(设置页展示)
    static let statement = """
    LinMinHao Chat 采用强制隐私模式:

    · 永久开启,无关闭按钮,无设置开关
    · 聊天界面不显示水印
    · 消息端到端加密:服务器只保存密文,没有私钥、没有万能密钥
    · 私钥仅保存在本机 Keychain,绝不上传
    · App 进入后台时自动模糊界面,应用切换器不泄露内容
    """
}
